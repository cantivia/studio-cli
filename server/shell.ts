import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { DATA_DIR } from './store.ts';

/**
 * zsh integration. Studio points ZDOTDIR at its own directory; each file there
 * sources the user's real one first, so their config loads as usual. .zshrc
 * then adds the Studio prompt (only over the stock macOS prompt; a custom
 * prompt or theme is left alone) and reports cwd via OSC 7.
 */
export const ZSH_DIR = path.join(DATA_DIR, 'zsh');

const passthrough = (file: string) => `# Generated by Studio CLI. Sources your own ${file}.
if [[ -f "\${STUDIO_USER_ZDOTDIR:-$HOME}/${file}" ]]; then
  _studio_zd=$ZDOTDIR; ZDOTDIR=\${STUDIO_USER_ZDOTDIR:-$HOME}
  source "$ZDOTDIR/${file}"
  STUDIO_USER_ZDOTDIR=$ZDOTDIR; ZDOTDIR=$_studio_zd; unset _studio_zd
fi
`;

const ZSHRC = `${passthrough('.zshrc')}
# ── Studio CLI shell integration ─────────────────────────────────────────────
autoload -Uz add-zsh-hook vcs_info
zstyle ':vcs_info:*' enable git
zstyle ':vcs_info:git:*' check-for-changes true
zstyle ':vcs_info:git:*' unstagedstr ' %F{#f59e0b}●'
zstyle ':vcs_info:git:*' stagedstr ' %F{#22c55e}+'
zstyle ':vcs_info:git:*' formats '%b%u%c'
zstyle ':vcs_info:git:*' actionformats '%b|%a%u%c'

zmodload zsh/datetime 2>/dev/null
_studio_preexec() { _studio_cmd="$1"; _studio_start=$EPOCHSECONDS }
add-zsh-hook preexec _studio_preexec

_studio_precmd() {
  local ex=$?
  # Long-running command finished: tell Studio (OSC 777), which rings the pane.
  if [[ -n "$_studio_start" ]]; then
    local d=$(( EPOCHSECONDS - _studio_start ))
    if (( d >= \${STUDIO_NOTIFY_AFTER:-10} )); then
      local c="\${_studio_cmd//;/,}"
      local verdict="Done in \${d}s"
      (( ex != 0 )) && verdict="Failed (exit $ex) after \${d}s"
      print -n "\\e]777;notify;\${c[1,60]};$verdict\\a"
    fi
    unset _studio_start
  fi
  vcs_info
  if [[ -n "$vcs_info_msg_0_" ]]; then
    _studio_git=" %F{244}on%f %F{\${STUDIO_ACCENT:-#8b5cf6}}\${vcs_info_msg_0_}%f"
  else
    _studio_git=""
  fi
  print -Pn "\\e]7;file://\${HOST}\${PWD// /%20}\\a"   # cwd for the sidebar
  print -Pn "\\e]2;%1~\\a"                            # pane title
}
add-zsh-hook precmd _studio_precmd

# Claude Code's theme follows the pane: light on paper terminals, dark on ink (your global setting is untouched).
if [[ -n "$STUDIO_CLAUDE_THEME" ]] && (( $+commands[claude] )); then
  claude() { command claude --settings '{"theme":"'"$STUDIO_CLAUDE_THEME"'"}' "$@"; }
fi

if [[ -z "$STUDIO_KEEP_PROMPT" && ( "$PROMPT" == '%n@%m %1~ %# ' || -z "$PROMPT" ) ]]; then
  setopt PROMPT_SUBST
  _sa="\${STUDIO_ACCENT:-#8b5cf6}"
  PROMPT=$'\\n'"%F{$_sa}%B%1~%b%f"'\${_studio_git}'$'\\n'"%(?.%F{$_sa}.%F{#e5383b})❯%f "
  RPROMPT='%(?..%F{#e5383b}%?%f )%F{244}%*%f'
  unset _sa
fi

# Studio's own command (studio notify, tell, peek…), also in the Mac app, which keeps it inside the app.
[[ -n "$STUDIO_BIN" ]] && path+=("$STUDIO_BIN")
`;

export function installShellIntegration() {
  fs.mkdirSync(ZSH_DIR, { recursive: true });
  for (const f of ['.zshenv', '.zprofile', '.zlogin']) fs.writeFileSync(path.join(ZSH_DIR, f), passthrough(f));
  fs.writeFileSync(path.join(ZSH_DIR, '.zshrc'), ZSHRC);
}

/** Env vars that route a zsh through the integration; empty for other shells. */
export function shellEnv(shell: string, accent?: string, theme?: string): Record<string, string> {
  if (!shell.endsWith('zsh')) return {};
  return {
    ...(theme === 'light' || theme === 'dark' ? { STUDIO_CLAUDE_THEME: theme } : {}),
    ZDOTDIR: ZSH_DIR,
    // Started from inside a Studio terminal, ZDOTDIR is that Studio's own folder (sourcing it would loop);
    // the real one is what that Studio remembered.
    STUDIO_USER_ZDOTDIR: process.env.STUDIO_USER_ZDOTDIR || process.env.ZDOTDIR || os.homedir(),
    ...(accent && /^#[0-9a-f]{6}$/i.test(accent) ? { STUDIO_ACCENT: accent } : {}),
  };
}
